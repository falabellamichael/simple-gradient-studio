'use strict';

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const mediaRoot = path.join(root, 'media');
const codiconRoot = path.join(root, 'node_modules', '@vscode', 'codicons', 'dist');
const outputPath = path.join(root, 'simplerag-extension', 'simple-gradient-studio-bundle.js');

const read = (filePath) => fs.readFileSync(filePath, 'utf8').replace(/\r\n/g, '\n');
const sha256 = (value) => crypto.createHash('sha256').update(value).digest('hex');

const studioHtmlSource = read(path.join(mediaRoot, 'studio.html'));
const studioCssSource = read(path.join(mediaRoot, 'studio.css'));
const studioScriptSource = read(path.join(mediaRoot, 'studio.js'));
const codiconCssSource = read(path.join(codiconRoot, 'codicon.css'));
const codiconFont = fs.readFileSync(path.join(codiconRoot, 'codicon.ttf'));

const studioHtml = studioHtmlSource
  .replace(/^\s*<meta http-equiv="Content-Security-Policy"[^>]*>\s*$/m, '')
  .replace(/^\s*<link rel="stylesheet" href="\{\{codiconUri\}\}">\s*$/m, '')
  .replace(/^\s*<link rel="stylesheet" href="\{\{cssUri\}\}[^>]*>\s*$/m, '')
  .replace(/^\s*<script nonce="\{\{nonce\}\}" src="\{\{scriptUri\}\}[^>]*><\/script>\s*$/m, '')
  .replace('{{view}}', '__SIMPLE_GRADIENT_VIEW__');

const codiconCss = codiconCssSource.replace(
  /url\("\.\/codicon\.ttf\?[^"\r\n]+"\)/,
  `url("data:font/truetype;base64,${codiconFont.toString('base64')}")`
);

if (studioHtml.includes('{{') || !codiconCss.includes('data:font/truetype;base64,')) {
  throw new Error('SimpleGradient Studio bundle transformation did not consume every host placeholder.');
}

const payload = {
  schema: 'simple-gradient-studio-assets',
  version: 1,
  sources: {
    htmlSha256: sha256(studioHtmlSource),
    cssSha256: sha256(studioCssSource),
    scriptSha256: sha256(studioScriptSource),
    codiconCssSha256: sha256(codiconCssSource),
    codiconFontSha256: sha256(codiconFont)
  },
  html: studioHtml,
  css: `${codiconCss}\n${studioCssSource}`,
  script: studioScriptSource
};

const output = [
  '/* Generated by scripts/build-simplerag-studio-bundle.cjs from the canonical Studio assets. */',
  '(function exposeSimpleGradientStudioAssets(global) {',
  "  'use strict';",
  `  global.__SIMPLE_GRADIENT_STUDIO_ASSETS__ = Object.freeze(${JSON.stringify(payload)});`,
  "})(typeof window !== 'undefined' ? window : globalThis);",
  ''
].join('\n');

fs.writeFileSync(outputPath, output, 'utf8');
process.stdout.write(`${path.relative(root, outputPath)} ${Buffer.byteLength(output)} bytes\n`);

const manifestPath = path.join(root, 'simplerag-extension', 'manifest.json');
if (fs.existsSync(manifestPath)) {
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  for (const asset of [...manifest.scripts, ...manifest.styles]) {
    const assetFilePath = path.join(root, 'simplerag-extension', asset.path);
    if (fs.existsSync(assetFilePath)) {
      const assetBytes = fs.readFileSync(assetFilePath);
      asset.size = assetBytes.length;
      asset.sha256 = crypto.createHash('sha256').update(assetBytes).digest('hex');
    }
  }
  fs.writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
  process.stdout.write(`Updated ${path.relative(root, manifestPath)}\n`);
}
